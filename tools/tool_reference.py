"""Render the README's MCP tool reference from the real tool schemas (code_guardian.mcp_server.TOOL_SPECS).

    python tools/tool_reference.py            # print the reference
    python tools/tool_reference.py --write    # replace the block between the markers in README.md

tests/test_tool_docs.py fails when README.md and TOOL_SPECS disagree, so edit the specs and re-run --write.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from code_guardian.mcp_server import TOOL_SPECS  # noqa: E402

START = "<!-- tool-reference:start (generated by tools/tool_reference.py; do not edit by hand) -->"
END = "<!-- tool-reference:end -->"
HINTS = ("readOnlyHint", "destructiveHint", "idempotentHint", "openWorldHint")


def _cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def _type(prop):
    if "enum" in prop:
        return " \\| ".join("`%s`" % v for v in prop["enum"])
    kind = prop["type"]
    if "minimum" in prop:
        kind += " ≥ %s" % prop["minimum"]
    return kind


def render(specs=TOOL_SPECS):
    out = [START, ""]
    for spec in specs:
        ann = spec["annotations"]
        required = set(spec["inputSchema"].get("required", []))
        out.append("#### `%s`: %s" % (spec["name"], spec["title"]))
        out.append("")
        out.append(spec["description"])
        out.append("")
        out.append("Annotations: " + ", ".join("`%s: %s`" % (h, json.dumps(ann[h])) for h in HINTS))
        out.append("")
        out.append("| parameter | type | required | default | description | example |")
        out.append("|---|---|---|---|---|---|")
        for name, prop in spec["inputSchema"]["properties"].items():
            default = "`%s`" % json.dumps(prop["default"]) if "default" in prop else "none"
            out.append("| `%s` | %s | %s | %s | %s | `%s` |" % (
                name, _type(prop), "yes" if name in required else "no", default, _cell(prop["description"]),
                _cell(json.dumps(prop["examples"][0]))))
        out.append("")
    out.append(END)
    return "\n".join(out)


def readme_block(text):
    """The generated block as it stands in README text, markers included, or None."""
    if START not in text or END not in text:
        return None
    return text[text.index(START):text.index(END) + len(END)]


def main(argv):
    block = render()
    if "--write" not in argv:
        print(block)
        return 0
    path = ROOT / "README.md"
    text = path.read_text(encoding="utf-8")
    old = readme_block(text)
    if old is None:
        print("README.md has no tool-reference markers", file=sys.stderr)
        return 1
    path.write_text(text.replace(old, block), encoding="utf-8", newline="\n")
    print("README.md tool reference: %d tools" % len(TOOL_SPECS))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
